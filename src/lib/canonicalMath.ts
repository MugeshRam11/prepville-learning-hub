import katex from 'katex';

/**
 * PrepVille Canonical Mathematical Pipeline
 * Standardized serialization, normalization, parsing, validation, and rendering contracts.
 *
 * STORAGE STANDARDS:
 * 1. Pure Mathematical Expressions:
 *    Standard LaTeX without surrounding delimiters.
 *    Example: \frac{-b \pm \sqrt{b^2-4ac}}{2a}
 *
 * 2. Mixed Prose & Mathematics:
 *    Prose with inline ($...$) or display ($$...$$) LaTeX delimiters.
 *    Example: Solve $2x + 3 = 11$ for $x$.
 *
 * FORBIDDEN NEW FORMATS:
 * - [[EQ:id]] token references
 * - Raw HTML equation chips (<span class="math-expression">...</span>)
 * - HTML generated by KaTeX
 * - Escaped JSON strings pretending to be mathematical content
 * - Parallel equation arrays without atomic persistence
 */

export type MathSegmentType = 'text' | 'inline-math' | 'display-math';

export interface MathSegment {
  type: MathSegmentType;
  value: string; // Plain text or pure LaTeX (without delimiters)
  raw: string;   // Original raw slice
}

export interface CanonicalMathValidationResult {
  isValid: boolean;
  errors: string[];
  normalized: string;
}

export interface LegacyEquationItem {
  id: string;
  latex: string;
  mathml?: string;
  renderedHtml?: string;
}

/**
 * Normalizes pure LaTeX expressions:
 * - Strips accidental surrounding delimiters ($...$, $$...$$, \(...\), \[...\])
 * - Normalizes excessive or inconsistent whitespace
 * - Preserves semantic math commands, sub/superscripts, matrices, environments
 */
export function normalizePureLatex(input: string | null | undefined): string {
  if (!input) return '';
  let str = String(input).trim();

  // Strip JSON quoting if leaked
  if (
    (str.startsWith('"') && str.endsWith('"')) ||
    (str.startsWith("'") && str.endsWith("'"))
  ) {
    try {
      const parsed = JSON.parse(str);
      if (typeof parsed === 'string') str = parsed.trim();
    } catch {
      str = str.slice(1, -1).trim();
    }
  }

  // Strip surrounding display delimiters
  if (str.startsWith('$$') && str.endsWith('$$') && str.length >= 4) {
    str = str.slice(2, -2).trim();
  } else if (str.startsWith('\\[') && str.endsWith('\\]') && str.length >= 4) {
    str = str.slice(2, -2).trim();
  }
  // Strip surrounding inline delimiters
  else if (str.startsWith('$') && str.endsWith('$') && str.length >= 2 && !str.slice(1, -1).includes('$')) {
    str = str.slice(1, -1).trim();
  } else if (str.startsWith('\\(') && str.endsWith('\\)') && str.length >= 4) {
    str = str.slice(2, -2).trim();
  }

  // Normalize Unicode minus to standard hyphen-minus for LaTeX
  str = str.replace(/−/g, '-');
  // Normalize Unicode multiplication sign to \times if outside commands
  str = str.replace(/×/g, '\\times ');
  // Normalize Unicode division sign to \div
  str = str.replace(/÷/g, '\\div ');
  // Normalize placeholder squares
  str = str.replace(/□/g, '\\square ');

  // Collapse 3 or more spaces into single space, but preserve single newlines in multiline environments
  str = str.replace(/[ \t]{2,}/g, ' ').trim();

  return str;
}

/**
 * Serializes an expression as inline math: $latex$
 */
export function serializeInlineMath(latex: string): string {
  const norm = normalizePureLatex(latex);
  if (!norm) return '';
  return `$${norm}$`;
}

/**
 * Serializes an expression as display math: $$latex$$
 */
export function serializeDisplayMath(latex: string): string {
  const norm = normalizePureLatex(latex);
  if (!norm) return '';
  return `$$${norm}$$`;
}

/**
 * Converts legacy formats into canonical mixed prose and math:
 * - [[EQ:id]] tokens with lookup table or equations array
 * - Leaked HTML chips (<span class="math-expression" data-latex="...">...</span>)
 * - Leaked <span data-math-latex="...">...</span>
 * - KaTeX HTML wrappers (<span class="katex">...</span>)
 * - MathML tags (<math>...</math>)
 */
export function convertLegacyTokens(
  rawText: string | null | undefined,
  legacyEquations?: LegacyEquationItem[] | Record<string, string>
): string {
  if (!rawText) return '';
  let out = String(rawText);

  // Build equation lookup map
  const eqMap: Record<string, string> = {};
  if (Array.isArray(legacyEquations)) {
    for (const eq of legacyEquations) {
      if (eq?.id && eq?.latex) {
        eqMap[eq.id] = eq.latex;
      }
    }
  } else if (legacyEquations && typeof legacyEquations === 'object') {
    Object.assign(eqMap, legacyEquations);
  }

  // 1. Replace [[EQ:id]] placeholders
  out = out.replace(/\[\[EQ:([^\]]+)\]\]/g, (match, id) => {
    const foundLatex = eqMap[id];
    if (foundLatex) {
      return ` $${normalizePureLatex(foundLatex)}$ `;
    }
    return ''; // Remove orphaned equation token if missing
  });

  // 2. Replace HTML data-latex chips:
  // e.g. <span class="math-expression" data-latex="x^2">...</span>
  // Handles nested spans cleanly
  const mathChipRegex = /<(span|div)[^>]*data-(?:math-)?latex=(?:"([^"]*)"|'([^']*)')[^>]*>/gi;
  let chipMatch: RegExpExecArray | null;
  const chipReplacements: { start: number; end: number; latex: string; isDisplay: boolean }[] = [];

  while ((chipMatch = mathChipRegex.exec(out)) !== null) {
    const tag = chipMatch[1].toLowerCase();
    const latex = (chipMatch[2] ?? chipMatch[3] ?? '')
      .replace(/&quot;/g, '"')
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>');
    const isDisplay = chipMatch[0].includes('data-display="block"') || tag === 'div';
    const startIdx = chipMatch.index;
    const afterOpen = mathChipRegex.lastIndex;

    // Find matching closing tag
    let depth = 1;
    const closeRegex = new RegExp(`<${tag}[^>]*>|</${tag}>`, 'gi');
    closeRegex.lastIndex = afterOpen;
    let closeMatch: RegExpExecArray | null;
    let endIdx = out.length;

    while ((closeMatch = closeRegex.exec(out)) !== null) {
      if (closeMatch[0].startsWith('</')) {
        depth--;
        if (depth === 0) {
          endIdx = closeRegex.lastIndex;
          break;
        }
      } else {
        depth++;
      }
    }

    chipReplacements.push({ start: startIdx, end: endIdx, latex, isDisplay });
  }

  // Apply replacements in reverse order
  for (let i = chipReplacements.length - 1; i >= 0; i--) {
    const { start, end, latex, isDisplay } = chipReplacements[i];
    const norm = normalizePureLatex(latex);
    const replacement = norm
      ? isDisplay
        ? `\n$$${norm}$$\n`
        : ` $${norm}$ `
      : '';
    out = out.slice(0, start) + replacement + out.slice(end);
  }

  // 3. Strip residual KaTeX HTML and MathML blocks
  out = out.replace(/<span[^>]*class="[^"]*katex[^"]*"[^>]*>[\s\S]*?<\/span>/gi, '');
  out = out.replace(/<math[^>]*>[\s\S]*?<\/math>/gi, '');

  // 4. Convert <br> or <p> tags to newlines
  out = out.replace(/<br\s*\/?>/gi, '\n');
  out = out.replace(/<\/p>/gi, '\n');
  out = out.replace(/<p[^>]*>/gi, '');

  // 5. Strip any leftover HTML tags
  out = out.replace(/<\/?[a-z][^>]*>/gi, '');

  // 6. Decode common HTML entities
  out = out
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"');

  // Collapse multiple spaces but preserve newlines
  return out
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * Extracts clean string representation from various historical answer structures:
 * - Plain string
 * - `{ text: "...", equations: [...] }`
 * - `{ latex: "..." }`
 * - `{ value: "..." }`
 * - stringified JSON of any of the above
 */
export function extractCanonicalAnswerText(input: unknown): string {
  if (input === null || input === undefined) return '';

  let current = input;

  for (let i = 0; i < 3; i++) {
    if (typeof current === 'string') {
      const trimmed = current.trim();
      if (
        (trimmed.startsWith('{') && trimmed.endsWith('}')) ||
        (trimmed.startsWith('[') && trimmed.endsWith(']'))
      ) {
        try {
          current = JSON.parse(trimmed);
          continue;
        } catch {
          // not valid JSON, stop unpeeling
        }
      }
      break;
    }

    if (Array.isArray(current)) {
      if (current.length === 0) return '';
      if (current.length === 1) {
        current = current[0];
        continue;
      }
      return current.map(item => extractCanonicalAnswerText(item)).filter(Boolean).join(' ');
    }

    if (typeof current === 'object' && current !== null) {
      const obj = current as Record<string, unknown>;
      const legacyEqs = Array.isArray(obj.equations) ? (obj.equations as LegacyEquationItem[]) : undefined;

      if ('text' in obj && typeof obj.text === 'string') {
        return convertLegacyTokens(obj.text, legacyEqs);
      }
      if ('latex' in obj && typeof obj.latex === 'string') {
        return normalizePureLatex(obj.latex);
      }
      if ('value' in obj && typeof obj.value === 'string') {
        return convertLegacyTokens(obj.value, legacyEqs);
      }
      try {
        return JSON.stringify(current);
      } catch {
        return '';
      }
    }

    return String(current);
  }

  if (typeof current !== 'string') return '';
  return convertLegacyTokens(current);
}

/**
 * Splits mixed text into typed segments:
 * - 'text': prose (with escaped \$ preserved as literal $)
 * - 'inline-math': pure LaTeX without $ delimiters
 * - 'display-math': pure LaTeX without $$ delimiters
 *
 * Handles:
 * - Escaped dollar signs (\$50 -> prose "$50")
 * - Currency patterns ($50, $100.00) without false-positive inline math match
 * - Multiline display math ($$...$$ and \[...\])
 * - Inline math ($...$ and \(...\))
 */
export function parseMixedProseAndMath(text: string | null | undefined): MathSegment[] {
  if (!text) return [];

  const segments: MathSegment[] = [];

  // Match:
  // 1. Escaped dollar sign: \\\$
  // 2. Display math: \$\$[\s\S]+?\$\$ or \\\[[\s\S]+?\\\]
  // 3. Inline math: \$[^\$\n]+?\$ or \\\([\s\S]+?\\\)
  // 4. Currency pattern: \$(?=\d+(?:\.\d+)?(?:\s|$|[^\w$]))
  const tokenizerRegex = /(\\\$)|(\$\$[\s\S]+?\$\$|\\\[[\s\S]+?\\\])|(\$[^$\n]+?\$|\\\([\s\S]+?\\\)|\$(?=\d+(?:\.\d+)?(?:\s|[.,!?;:]|$)))/g;

  let lastIndex = 0;
  let match: RegExpExecArray | null;

  while ((match = tokenizerRegex.exec(text)) !== null) {
    const matchIndex = match.index;

    // Append preceding prose
    if (matchIndex > lastIndex) {
      const preceding = text.slice(lastIndex, matchIndex);
      if (preceding) {
        // Merge with previous text segment if possible
        if (segments.length > 0 && segments[segments.length - 1].type === 'text') {
          segments[segments.length - 1].value += preceding;
          segments[segments.length - 1].raw += preceding;
        } else {
          segments.push({ type: 'text', value: preceding, raw: preceding });
        }
      }
    }

    const [fullMatch, escapedDollar, displayBlock, inlineOrCurrency] = match;

    if (escapedDollar) {
      // Literal dollar sign in prose
      if (segments.length > 0 && segments[segments.length - 1].type === 'text') {
        segments[segments.length - 1].value += '$';
        segments[segments.length - 1].raw += fullMatch;
      } else {
        segments.push({ type: 'text', value: '$', raw: fullMatch });
      }
      lastIndex = tokenizerRegex.lastIndex;
      continue;
    }

    if (displayBlock) {
      let latex = '';
      if (displayBlock.startsWith('$$')) {
        latex = displayBlock.slice(2, -2);
      } else if (displayBlock.startsWith('\\[')) {
        latex = displayBlock.slice(2, -2);
      }
      segments.push({
        type: 'display-math',
        value: normalizePureLatex(latex),
        raw: fullMatch,
      });
      lastIndex = tokenizerRegex.lastIndex;
      continue;
    }

    if (inlineOrCurrency) {
      // Check if this is a standalone currency dollar sign like "$50"
      if (inlineOrCurrency === '$') {
        // It's a bare dollar sign that precedes a number (currency)
        if (segments.length > 0 && segments[segments.length - 1].type === 'text') {
          segments[segments.length - 1].value += '$';
          segments[segments.length - 1].raw += '$';
        } else {
          segments.push({ type: 'text', value: '$', raw: '$' });
        }
        lastIndex = tokenizerRegex.lastIndex;
        continue;
      }

      // Inline math: $latex$ or \(latex\)
      let latex = '';
      if (inlineOrCurrency.startsWith('$') && inlineOrCurrency.endsWith('$')) {
        latex = inlineOrCurrency.slice(1, -1);
      } else if (inlineOrCurrency.startsWith('\\(') && inlineOrCurrency.endsWith('\\)')) {
        latex = inlineOrCurrency.slice(2, -2);
      }

      segments.push({
        type: 'inline-math',
        value: normalizePureLatex(latex),
        raw: fullMatch,
      });
      lastIndex = tokenizerRegex.lastIndex;
      continue;
    }

    lastIndex = tokenizerRegex.lastIndex;
  }

  // Trailing prose
  if (lastIndex < text.length) {
    const trailing = text.slice(lastIndex);
    if (trailing) {
      if (segments.length > 0 && segments[segments.length - 1].type === 'text') {
        segments[segments.length - 1].value += trailing;
        segments[segments.length - 1].raw += trailing;
      } else {
        segments.push({ type: 'text', value: trailing, raw: trailing });
      }
    }
  }

  return segments;
}

/**
 * Validates a LaTeX mathematical expression for syntactic balance and KaTeX parseability.
 */
export function validateMathExpression(latex: string): CanonicalMathValidationResult {
  const norm = normalizePureLatex(latex);
  const errors: string[] = [];

  if (!norm) {
    return { isValid: false, errors: ['Expression is empty'], normalized: '' };
  }

  // 1. Check brace balancing ({ and })
  let braceCount = 0;
  for (let i = 0; i < norm.length; i++) {
    const ch = norm[i];
    // Check if escaped
    if (ch === '{' && (i === 0 || norm[i - 1] !== '\\')) braceCount++;
    if (ch === '}' && (i === 0 || norm[i - 1] !== '\\')) braceCount--;
    if (braceCount < 0) {
      errors.push('Unmatched closing brace }');
      break;
    }
  }
  if (braceCount > 0) {
    errors.push('Unclosed opening brace {');
  }

  // 2. Check \begin{env} and \end{env} matching
  const beginMatches = Array.from(norm.matchAll(/\\begin\{([^}]+)\}/g)).map(m => m[1]);
  const endMatches = Array.from(norm.matchAll(/\\end\{([^}]+)\}/g)).map(m => m[1]);
  if (beginMatches.length !== endMatches.length) {
    errors.push(`Mismatched environments: ${beginMatches.length} \\begin vs ${endMatches.length} \\end`);
  }

  // 3. Test KaTeX parseability
  try {
    katex.renderToString(norm, {
      throwOnError: true,
      strict: false,
    });
  } catch (err: any) {
    errors.push(err?.message || 'KaTeX parsing error');
  }

  return {
    isValid: errors.length === 0,
    errors,
    normalized: norm,
  };
}

/**
 * Round-trip equivalence testing utility:
 * Input -> Serialization -> Storage Representation -> Restoration
 */
export function testRoundTripEquivalence(
  input: string,
  mode: 'pure_latex' | 'mixed_prose'
): { success: boolean; errors: string[]; restored: string } {
  const errors: string[] = [];

  if (mode === 'pure_latex') {
    const normalized = normalizePureLatex(input);
    const validation = validateMathExpression(normalized);
    if (!validation.isValid) {
      errors.push(...validation.errors);
    }
    const restored = normalizePureLatex(normalized);
    if (restored !== normalized) {
      errors.push(`Restoration divergence: expected "${normalized}", got "${restored}"`);
    }
    return {
      success: errors.length === 0,
      errors,
      restored,
    };
  }

  // Mixed prose mode
  const segments = parseMixedProseAndMath(input);
  const reassembled = segments
    .map(seg => {
      if (seg.type === 'inline-math') return `$${seg.value}$`;
      if (seg.type === 'display-math') return `$$${seg.value}$$`;
      // Escape dollar signs if they appear in prose
      return seg.value.replace(/\$/g, '\\$');
    })
    .join('');

  const reParsed = parseMixedProseAndMath(reassembled);

  if (segments.length !== reParsed.length) {
    errors.push(`Segment count mismatch: original has ${segments.length}, reassembled has ${reParsed.length}`);
  } else {
    for (let i = 0; i < segments.length; i++) {
      if (segments[i].type !== reParsed[i].type || segments[i].value !== reParsed[i].value) {
        errors.push(
          `Segment ${i} mismatch: [${segments[i].type}] "${segments[i].value}" vs [${reParsed[i].type}] "${reParsed[i].value}"`
        );
      }
    }
  }

  return {
    success: errors.length === 0,
    errors,
    restored: reassembled,
  };
}
